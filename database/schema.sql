SET NAMES utf8mb4;

CREATE TABLE IF NOT EXISTS Users (
 user_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, username VARCHAR(80) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS Trips (
 trip_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, user_id INT UNSIGNED NOT NULL,
 title VARCHAR(140) NOT NULL, destination VARCHAR(180) NOT NULL, start_date DATE NOT NULL, end_date DATE NOT NULL,
 budget_limit DECIMAL(12,2) NULL, cover_path VARCHAR(255) NULL, notes TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_trips_user FOREIGN KEY (user_id) REFERENCES Users(user_id) ON DELETE CASCADE,
 INDEX idx_trips_user_dates (user_id,start_date,end_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS Places (
 place_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, trip_id INT UNSIGNED NOT NULL,
 place_name VARCHAR(140) NOT NULL, category VARCHAR(80) NULL, address VARCHAR(255) NULL, notes TEXT NULL,
 planned_cost DECIMAL(12,2) NULL, status ENUM('planned','visited') NOT NULL DEFAULT 'planned',
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_places_trip FOREIGN KEY (trip_id) REFERENCES Trips(trip_id) ON DELETE CASCADE,
 INDEX idx_places_trip_status (trip_id,status)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS Tickets (
 ticket_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, trip_id INT UNSIGNED NOT NULL,
 title VARCHAR(160) NOT NULL, ticket_type VARCHAR(80) NULL, use_date DATE NULL,
 file_path VARCHAR(255) NOT NULL, file_extension VARCHAR(10) NOT NULL, original_name VARCHAR(255) NOT NULL,
 notes TEXT NULL, is_pinned TINYINT(1) NOT NULL DEFAULT 0, cost DECIMAL(12,2) NULL,
 include_in_expenses TINYINT(1) NOT NULL DEFAULT 0,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_tickets_trip FOREIGN KEY (trip_id) REFERENCES Trips(trip_id) ON DELETE CASCADE,
 INDEX idx_tickets_trip_pinned (trip_id,is_pinned)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS Expenses (
 expense_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, trip_id INT UNSIGNED NOT NULL,
 place_id INT UNSIGNED NULL, ticket_id INT UNSIGNED NULL, title VARCHAR(160) NOT NULL,
 amount DECIMAL(12,2) NOT NULL, category VARCHAR(80) NOT NULL, expense_date DATE NOT NULL, notes TEXT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 CONSTRAINT fk_expenses_trip FOREIGN KEY (trip_id) REFERENCES Trips(trip_id) ON DELETE CASCADE,
 CONSTRAINT fk_expenses_place FOREIGN KEY (place_id) REFERENCES Places(place_id) ON DELETE SET NULL,
 CONSTRAINT fk_expenses_ticket FOREIGN KEY (ticket_id) REFERENCES Tickets(ticket_id) ON DELETE CASCADE,
 UNIQUE KEY uq_expenses_ticket (ticket_id), INDEX idx_expenses_trip_date (trip_id,expense_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS Photos (
 photo_id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY, trip_id INT UNSIGNED NOT NULL,
 file_path VARCHAR(255) NOT NULL, caption VARCHAR(180) NULL, photo_date DATE NULL, description TEXT NULL,
 is_cover TINYINT(1) NOT NULL DEFAULT 0, created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT fk_photos_trip FOREIGN KEY (trip_id) REFERENCES Trips(trip_id) ON DELETE CASCADE,
 INDEX idx_photos_trip_date (trip_id,photo_date)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

